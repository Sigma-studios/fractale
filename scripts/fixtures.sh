#!/usr/bin/env bash
# Build Fractale's test tree.
#   scripts/fixtures.sh [DIR]      (default: target/fixtures)
# Deep and wide folders, a 10k-file folder, a 5k-image folder, sparse files,
# hard links, unreadable folders, symlinks (loops, dangling), long names,
# spaces and emoji. Non-UTF-8 names only on Linux (APFS refuses them).
# Safe to rerun: it only ever writes inside DIR.
set -euo pipefail
DIR=${1:-$(cd "$(dirname "$0")/.." && pwd)/target/fixtures}
mkdir -p "$DIR"
cd "$DIR"
# Restore permissions a previous run took away, so a rebuild can replace it.
chmod -R u+rwx . 2>/dev/null || true

python3 -I - "$DIR" <<'PY'
import os, random, sys
root = sys.argv[1]
random.seed(42)

def write(path, size, fill=b"x"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write((fill * (size // len(fill) + 1))[:size])

# Projects with a realistic shape: big build outputs, sources, assets.
for p, (target_mb, src_files) in {"bevy_ticked": (64, 120), "socks": (40, 60), "bevy_factory": (24, 80), "notes": (0, 15)}.items():
    base = os.path.join(root, "Projects", p)
    for i in range(src_files):
        write(os.path.join(base, "src", f"mod_{i}.rs"), random.randint(200, 20000), b"fn main() {}\n")
    if target_mb:
        for i in range(target_mb):
            write(os.path.join(base, "target", "debug", "deps", f"lib{p}_{i}.rlib"), 1 << 20)
    write(os.path.join(base, "Cargo.toml"), 300, b"[package]\n")
    write(os.path.join(base, "README.md"), 2000, b"# readme\n")

# Deep: 40 levels.
d = os.path.join(root, "deep")
for i in range(40):
    d = os.path.join(d, f"level{i:02d}")
write(os.path.join(d, "bottom.txt"), 100)

# Wide: 1000 folders of varied sizes.
for i in range(1000):
    write(os.path.join(root, "wide", f"folder{i}", "data.bin"), random.choice([0, 100, 4096, 50000, 300000]))

# 10k files in one folder, natural-sort bait included.
big = os.path.join(root, "big10k")
for i in range(10000):
    write(os.path.join(big, f"file{i}.log"), random.randint(0, 9000), b"log line\n")

# Names: long, spaces, emoji, accents, leading dots, natural order.
names = os.path.join(root, "names")
for n in ["a file with spaces.txt", "émoji 🎉 party.md", "Été 2024", "file2.txt", "file10.txt", "file1.txt",
          ".hidden-file", ".hidden-dir/inside.txt", "UPPER.TXT", "x" * 250 + ".txt", "ünïcödé/deep.txt"]:
    write(os.path.join(names, n), random.randint(1, 5000))
print("python part done")
PY

# Sparse: 1 GiB apparent, a few KiB allocated.
mkdir -p sparse
truncate -s 1G sparse/disk.img
printf 'data' | dd of=sparse/disk.img bs=1 seek=$((512 << 20)) conv=notrunc 2>/dev/null

# Hard links inside one folder and across folders.
mkdir -p links/a links/b
head -c 3000000 /dev/zero > links/a/original.bin
ln -f links/a/original.bin links/a/same-folder-link.bin
ln -f links/a/original.bin links/b/other-folder-link.bin

# Symlinks: to a file, to a folder, dangling, and a loop.
mkdir -p symlinks
ln -sfn ../names/file1.txt symlinks/to-file
ln -sfn ../Projects symlinks/to-folder
ln -sfn ../does/not/exist symlinks/dangling
ln -sfn loop-b symlinks/loop-a
ln -sfn loop-a symlinks/loop-b

# Unreadable: no permission at all, and listable but not searchable.
mkdir -p locked/secret noexec
head -c 50000 /dev/zero > locked/secret/data.bin
head -c 10000 /dev/zero > noexec/inside.bin
chmod 000 locked
chmod 644 noexec

# Non-UTF-8 names (Linux only).
if [ "$(uname)" = Linux ]; then
    mkdir -p "names/$(printf 'caf\xe9')"
    head -c 1234 /dev/zero > "names/$(printf 'latin1-\xe9t\xe9.txt')"
fi

# Images (M4): generated by the Rust helper when it exists.
if [ -f "$(dirname "$0")/../examples/make_images.rs" ] && [ ! -d images5k ]; then
    (cd "$(dirname "$0")/.." && cargo run --quiet --release --example make_images -- "$DIR/images5k" 5000)
fi
echo "fixtures in $DIR"
